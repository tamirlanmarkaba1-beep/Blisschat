package com.bliss.blisschat.data.crypto

import com.bliss.blisschat.data.Chat
import com.bliss.blisschat.data.ChatType
import com.bliss.blisschat.data.Content
import com.bliss.blisschat.data.Envelope
import com.google.firebase.firestore.FirebaseFirestore
import kotlinx.coroutines.tasks.await
import java.util.concurrent.ConcurrentHashMap

/**
 * End-to-end encryption, used ONLY by secret chats (Chat.secret). Ordinary chats, groups and channels are stored as
 * plain JSON ([plain]); old encrypted messages of those chats are still opened with the keys when this phone has them.
 *
 * Direct chats: key = HKDF(ECDH(myPrivate, peerPublic)). Only the two phones can compute it.
 * Group chats : a random AES-256 group key is generated by the creator and "wrapped" separately
 *               for every member with that member's pairwise ECDH key (stored in chats/{id}/keys/{uid}).
 * Media       : every file gets its own random key; the key travels inside the (encrypted) message.
 *
 * The server only ever sees public keys, wrapped keys and ciphertext.
 */
class E2EE(private val keys: LocalKeys) {

    private val db get() = FirebaseFirestore.getInstance()
    private val pubCache = ConcurrentHashMap<String, ByteArray>()
    private val kidCache = ConcurrentHashMap<String, Pair<String, Long>>()
    private val keyCache = ConcurrentHashMap<String, ByteArray>()
    private val botCache = ConcurrentHashMap<String, Boolean>()
    private val groupFail = ConcurrentHashMap<String, Long>()

    suspend fun isBot(uid: String): Boolean {
        botCache[uid]?.let { return it }
        val doc = runCatching { db.collection("users").document(uid).get().await() }.getOrNull()
        val b = doc?.getBoolean("bot") == true || doc?.getString("username")?.endsWith("_bot") == true
        botCache[uid] = b
        return b
    }

    /* ------------------------------------------------------------ own key */

    /** Makes sure this device has a key pair and that its public half is published. */
    suspend fun ensureKeys(uid: String, publishToProfile: Boolean): LocalKey {
        val local = keys.current(uid) ?: keys.create(uid)
        val pub = Crypto.b64(local.publicX509)
        db.collection("users").document(uid).collection("keys").document(local.kid)
            .set(mapOf("publicKey" to pub)).await()
        if (publishToProfile) {
            db.collection("users").document(uid)
                .update(mapOf("publicKey" to pub, "kid" to local.kid)).await()
        }
        return local
    }

    fun localKey(uid: String): LocalKey? = keys.current(uid)

    /* ------------------------------------------------------------ peer keys */

    suspend fun publicKey(uid: String, kid: String): ByteArray {
        pubCache["$uid:$kid"]?.let { return it }
        val doc = db.collection("users").document(uid).collection("keys").document(kid).get().await()
        val s = doc.getString("publicKey") ?: throw CryptoException("Нет открытого ключа собеседника")
        val bytes = Crypto.unb64(s)
        pubCache["$uid:$kid"] = bytes
        return bytes
    }

    suspend fun currentKid(uid: String): String {
        val cached = kidCache[uid]
        if (cached != null && System.currentTimeMillis() - cached.second < 60_000) return cached.first
        val kid = db.collection("users").document(uid).get().await().getString("kid").orEmpty()
        if (kid.isEmpty()) throw CryptoException("У собеседника ещё нет ключа шифрования")
        val resolvedKid = kid
        kidCache[uid] = resolvedKid to System.currentTimeMillis()
        return resolvedKid
    }

    /** Pairwise symmetric key between one of my keys and one of the peer's keys. */
    suspend fun pairKey(me: String, myKid: String, peer: String, peerKid: String, salt: String): ByteArray {
        val id = "$me:$myKid:$peer:$peerKid:$salt"
        keyCache[id]?.let { return it }
        val mine = keys.find(me, myKid) ?: keys.current(me) ?: throw CryptoException("На этом устройстве нет ключа шифрования")
        val peerPub = publicKey(peer, peerKid)
        val shared = Crypto.agree(mine.priv, peerPub)
        val key = Crypto.hkdf(shared, salt.toByteArray(), "blisschat-pair-v1".toByteArray())
        keyCache[id] = key
        return key
    }

    /* ------------------------------------------------------------ group keys */

    /**
     * The group key, unwrapped with MY key. Throws [CryptoException] when it is missing or was wrapped for a key this
     * device no longer has (new phone without backup): never invents a random key, because messages encrypted with
     * it could not be read by anybody.
     */
    suspend fun groupKey(chatId: String, me: String): ByteArray {
        keyCache["g:$chatId"]?.let { return it }
        // a failed lookup is remembered for a few seconds so a chat with hundreds of unreadable messages doesn't hit the server for each one
        val failedAt = groupFail[chatId]
        if (failedAt != null && System.currentTimeMillis() - failedAt < 15_000) throw CryptoException("Нет ключа группы")
        try {
            return loadGroupKey(chatId, me)
        } catch (e: Exception) {
            groupFail[chatId] = System.currentTimeMillis()
            throw e
        }
    }

    private suspend fun loadGroupKey(chatId: String, me: String): ByteArray {
        val doc = db.collection("chats").document(chatId).collection("keys").document(me).get().await()
        val wrapped = doc.getString("wrapped") ?: throw CryptoException("Нет ключа группы")
        val by = doc.getString("by").orEmpty()
        val mkid = doc.getString("mkid").orEmpty()
        if (keys.find(me, mkid) == null) throw CryptoException("Ключ группы создан для другого устройства")
        val key = pairKey(me, mkid, by, doc.getString("bkid").orEmpty(), "gk:$chatId")
        val gk = Crypto.open(key, Crypto.unb64(wrapped), "gk:$chatId:$me".toByteArray())
        keyCache["g:$chatId"] = gk
        return gk
    }

    suspend fun groupKeyOrNull(chatId: String, me: String): ByteArray? = runCatching { groupKey(chatId, me) }.getOrNull()

    /** Forget the cached key of a group so that the next use reads the (possibly re-issued) key from the server. */
    fun forgetGroup(chatId: String) { keyCache.remove("g:$chatId"); groupFail.remove(chatId) }

    /**
     * Members who changed phone / re-installed have a new key, so their copy of the group key is useless.
     * Whoever can still read the group key re-wraps it for them (like WhatsApp re-sharing sender keys).
     */
    suspend fun repairGroup(chat: Chat, me: String) {
        val gk = groupKeyOrNull(chat.id, me) ?: return
        if (chat.members.size > 60) return
        val col = db.collection("chats").document(chat.id).collection("keys")
        for (uid in chat.members) {
            if (uid == me || isBot(uid)) continue
            runCatching {
                val kid = db.collection("users").document(uid).get().await().getString("kid").orEmpty()
                if (kid.isEmpty()) return@runCatching
                val doc = col.document(uid).get().await()
                if (doc.exists() && doc.getString("mkid") == kid) return@runCatching
                col.document(uid).set(wrapGroupKey(chat.id, me, gk, uid, kid)).await()
            }
        }
    }

    /**
     * Last resort when nobody can read the old group key any more: issue a fresh key to every member.
     * Messages written with the old key stay unreadable.
     */
    suspend fun resetGroupKey(chat: Chat, me: String) {
        val mine = ensureKeys(me, publishToProfile = false)
        val gk = Crypto.randomKey()
        val col = db.collection("chats").document(chat.id).collection("keys")
        // my own copy first (rules require the author to be a member), then everybody else
        col.document(me).set(wrapGroupKey(chat.id, me, gk, me, mine.kid)).await()
        for (uid in chat.members) {
            if (uid == me || isBot(uid)) continue
            runCatching {
                val kid = db.collection("users").document(uid).get().await().getString("kid").orEmpty()
                if (kid.isNotEmpty()) col.document(uid).set(wrapGroupKey(chat.id, me, gk, uid, kid)).await()
            }
        }
        keyCache["g:${chat.id}"] = gk
        groupFail.remove(chat.id)
    }

    /** Wraps the group key for one member, returning the Firestore document to store. */
    suspend fun wrapGroupKey(chatId: String, me: String, groupKey: ByteArray, target: String, targetKid: String): Map<String, Any> {
        val mine = keys.current(me) ?: throw CryptoException("На этом устройстве нет ключа шифрования")
        val key = pairKey(me, mine.kid, target, targetKid, "gk:$chatId")
        val wrapped = Crypto.seal(key, groupKey, "gk:$chatId:$target".toByteArray())
        return mapOf("wrapped" to Crypto.b64(wrapped), "by" to me, "bkid" to mine.kid, "mkid" to targetKid)
    }

    fun rememberGroupKey(chatId: String, key: ByteArray) { keyCache["g:$chatId"] = key; groupFail.remove(chatId) }

    /* ------------------------------------------------------------ messages */

    /** Ordinary messages are stored as readable JSON (ciphertext is base64 and can never start with a brace). */
    private fun isPlain(env: Envelope) = env.ct.trimStart().startsWith("{")

    suspend fun encrypt(chat: Chat, me: String, content: Content): Envelope {
        if (!chat.secret) return Envelope(content.toJson(), "", "")
        val plain = content.toJson().toByteArray()
        val aad = chat.id.toByteArray()
        return if (chat.type == ChatType.DIRECT) {
            val peer = chat.peerOf(me) ?: throw CryptoException("Нет собеседника")
            if (isBot(peer)) {
                return Envelope(content.toJson(), "", "")
            }
            val mine = keys.current(me) ?: throw CryptoException("На этом устройстве нет ключа шифрования")
            val peerKid = currentKid(peer)
            val key = pairKey(me, mine.kid, peer, peerKid, chat.id)
            Envelope(Crypto.b64(Crypto.seal(key, plain, aad)), mine.kid, peerKid)
        } else {
            Envelope(Crypto.b64(Crypto.seal(groupKey(chat.id, me), plain, aad)))
        }
    }

    /** Null when this phone cannot read the message (no key / wrong key / tampered). */
    suspend fun decryptOrNull(chat: Chat, me: String, senderId: String, env: Envelope): Content? {
        if (isPlain(env)) return runCatching { Content.fromJson(env.ct) }.getOrNull()
        val aad = chat.id.toByteArray()
        return runCatching {
            val bytes = if (chat.type == ChatType.DIRECT) {
                val peer = chat.peerOf(me) ?: throw CryptoException("Нет собеседника")
                if (isBot(peer)) {
                    return Content.fromJson(env.ct)
                }
                val fromMe = senderId == me
                val key = pairKey(me, if (fromMe) env.a else env.b, peer, if (fromMe) env.b else env.a, chat.id)
                Crypto.open(key, Crypto.unb64(env.ct), aad)
            } else {
                Crypto.open(groupKey(chat.id, me), Crypto.unb64(env.ct), aad)
            }
            Content.fromJson(String(bytes))
        }.getOrNull()
    }

    suspend fun decrypt(chat: Chat, me: String, senderId: String, env: Envelope): Content =
        decryptOrNull(chat, me, senderId, env) ?: Content(Content.KIND_TEXT, text = "🔒 Зашифрованное сообщение")

    /* ------------------------------------------------------------ media */

    /** @return ciphertext and the base64 file key (the key is sent inside the encrypted message). */
    fun encryptMedia(plain: ByteArray): Pair<ByteArray, String> {
        val key = Crypto.randomKey()
        return Crypto.seal(key, plain) to Crypto.b64(key)
    }

    fun decryptMedia(cipher: ByteArray, keyB64: String): ByteArray = Crypto.open(Crypto.unb64(keyB64), cipher)

    /* ------------------------------------------------------------ calls */

    fun seal(key: ByteArray, text: String, aad: String): String =
        Crypto.b64(Crypto.seal(key, text.toByteArray(), aad.toByteArray()))

    fun open(key: ByteArray, b64: String, aad: String): String =
        String(Crypto.open(key, Crypto.unb64(b64), aad.toByteArray()))
}
